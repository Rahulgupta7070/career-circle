package Array;


public class swap {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        // Swapping logic
        int temp = a;
        a = b;
        b = temp;

        System.out.println("a: " + a); // Outputs 20
        System.out.println("b: " + b); // Outputs 10
    }
}

